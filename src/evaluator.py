def build_col_rename_map(
    db_id: str,
    data_dir: str,
    semantic_level: int,
) -> Optional[Dict[str, List[Tuple[str, str]]]]:
    """
    Build a {table: [(original_col, mapped_col), ...]} mapping for the given
    database and semantic level.

    Returns None when semantic_level == 3 AND all mapped names equal the
    original names (no views are needed).  For S1/S2/S4 and any database
    where names differ, returns the full mapping.

    The caller passes this to evaluate() so the evaluator knows how to
    translate the LLM's SQL back to real column names.
    """
    from src.column_aliases import get_name as _alias

    tables_path = Path(data_dir) / "dev_tables.json"
    with open(tables_path, encoding="utf-8") as f:
        all_entries = json.load(f)
    entry = next(t for t in all_entries if t["db_id"] == db_id)

    table_names = entry["table_names_original"]
    col_names_original = entry["column_names_original"]  # [(table_idx, col_name), ...]

    # Group original column names by table (in order)
    cols_by_table: Dict[str, List[str]] = {t: [] for t in table_names}
    for table_idx, col_name in col_names_original:
        if table_idx == -1:
            continue
        cols_by_table[table_names[table_idx]].append(col_name)

    rename_map: Dict[str, List[Tuple[str, str]]] = {}
    any_changed = False

    for table, orig_cols in cols_by_table.items():
        pairs: List[Tuple[str, str]] = []
        for col_pos, orig in enumerate(orig_cols):
            if semantic_level == 1:
                # positional: col_a, col_b, …
                from src.schema_builder import _idx_to_label
                mapped = f"col_{_idx_to_label(col_pos)}"
            else:
                mapped = _alias(db_id, orig, semantic_level)

            pairs.append((orig, mapped))
            if mapped != orig:
                any_changed = True
        rename_map[table] = pairs

    # If nothing changed (all names identical), no views needed → return None
    return rename_map if any_changed else None


def build_l1_col_rename_map(
    db_id: str,
    data_dir: str,
    semantic_level: int,
) -> Optional[Dict[str, List[Tuple[str, str]]]]:
    """
    Column rename map for L1: physical names in ``{db_id}__1nf.sqlite`` (S3-style)
    → display names shown in the prompt at *semantic_level*.

    Same idea as ``build_col_rename_map`` for L3–L6, but for the single wide table
    ``one_nf_0``.
    """
    from preprocess_data.to_1nf.convert import build_plan
    from src.schema_builder import L1_TABLE_NAME

    phys = build_plan(db_id, data_dir, semantic_level=3).display_columns
    disp = build_plan(db_id, data_dir, semantic_level=semantic_level).display_columns
    if phys == disp:
        return None
    return {L1_TABLE_NAME: list(zip(phys, disp))}


def build_l2_col_rename_map(
    db_id: str,
    data_dir: str,
    semantic_level: int,
) -> Optional[Dict[str, List[Tuple[str, str]]]]:
    """
    Column rename map for L2: physical names in ``{db_id}__2nf.sqlite`` (built at S3)
    → display names shown in the prompt at *semantic_level*, per cluster table.

    Returns None when every cluster uses identical physical and display names (S3).
    """
    from preprocess_data.to_2nf.convert import build_plan
    from preprocess_data.to_2nf.specs import SPECS

    if db_id not in SPECS:
        return None

    plan_phys = build_plan(db_id, data_dir, semantic_level=3)
    plan_disp = build_plan(db_id, data_dir, semantic_level=semantic_level)

    if len(plan_phys.clusters) != len(plan_disp.clusters):
        raise ValueError(f"2NF plan cluster count mismatch for db_id={db_id!r}")

    rename_map: Dict[str, List[Tuple[str, str]]] = {}
    any_changed = False
    for p_phys, p_disp in zip(plan_phys.clusters, plan_disp.clusters):
        if p_phys.output_table != p_disp.output_table:
            raise ValueError(
                f"2NF cluster table mismatch: {p_phys.output_table!r} vs "
                f"{p_disp.output_table!r}"
            )
        phys_cols = p_phys.display_columns
        disp_cols = p_disp.display_columns
        if phys_cols != disp_cols:
            rename_map[p_phys.output_table] = list(zip(phys_cols, disp_cols))
            any_changed = True

    return rename_map if any_changed else None


