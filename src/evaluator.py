def _build_pred_connection(
    db_path: str,
    col_rename_map: Dict[str, List[Tuple[str, str]]],
) -> sqlite3.Connection:
    """
    Open the physical SQLite DB and install TEMP VIEWs that shadow base tables
    with mapped column names (L3–L6 semantic renaming).
    """
    conn = sqlite3.connect(db_path)
    conn.text_factory = str
    if col_rename_map:
        for table, pairs in col_rename_map.items():
            select_parts = [
                f'main."{table}"."{orig_col}" AS `{mapped_col}`'
                for orig_col, mapped_col in pairs
            ]
            view_sql = (
                f'CREATE TEMP VIEW "{table}" AS '
                f'SELECT {", ".join(select_parts)} '
                f'FROM main."{table}"'
            )
            try:
                conn.execute(view_sql)
            except sqlite3.OperationalError as e:
                print(f"[evaluator] Warning: could not create TEMP VIEW for '{table}': {e}")
    return conn


def _execute(conn: sqlite3.Connection, sql: str, timeout_sec: float = _SQL_TIMEOUT_SEC) -> list:
    """Execute SQL and return all rows. Raises on error or timeout."""
    deadline = time.monotonic() + timeout_sec

    def _progress_handler() -> int:
        if time.monotonic() > deadline:
            return 1  # request interrupt
        return 0

    conn.set_progress_handler(_progress_handler, 10_000)
    try:
        cursor = conn.execute(sql)
        return cursor.fetchall()
    finally:
        conn.set_progress_handler(None, 0)


def _execute_safe(conn: sqlite3.Connection, sql: str):
    """
    Execute SQL without raising. Returns (rows, None) on success,
    (None, error_message) on failure.
    """
    try:
        rows = _execute(conn, sql)
        return rows, None
    except sqlite3.OperationalError as e:
        if "interrupted" in str(e).lower():
            return None, f"SQL execution timed out after {_SQL_TIMEOUT_SEC}s"
        return None, str(e)
    except Exception as e:
        return None, str(e)


def _result_sets_equal(pred_rows: list, gold_rows: list) -> bool:
    """
    Compare two result sets as multisets (Counter over normalised rows).
    Normalisation converts each value to a comparable string to avoid
    type mismatches between INTEGER 1 and REAL 1.0 representing the same value.
    """
    return Counter(_normalise(pred_rows)) == Counter(_normalise(gold_rows))


def _normalise(rows: list) -> list:
    """
    Convert each row to a tuple of normalised string values so that
    equivalent values with different Python types compare as equal.

    Examples:
      (1,)   and (1.0,)  → both become ('1',)    → equal
      (None,)            → ('',)
      ('YES',)           → ('yes',)               → case-insensitive
    """
    normalised = []
    for row in rows:
        norm_row = tuple(
            "" if v is None
            else str(float(v)).rstrip("0").rstrip(".") if _is_numeric(v)
            else str(v).strip().lower()
            for v in row
        )
        normalised.append(norm_row)
    return normalised


def _is_numeric(value) -> bool:
    """Return True if value is an int or float (not a string)."""
    return isinstance(value, (int, float)) and not isinstance(value, bool)


